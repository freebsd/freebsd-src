DEFINE_TEST(test_read_format_zip_negative_timestamp_pkware_unix)
{
	struct archive *a;
	struct archive_entry *ae;

	assert((a = archive_read_new()) != NULL);
	assertEqualIntA(a, ARCHIVE_OK,
	    archive_read_support_format_zip_seekable(a));
	assertEqualIntA(a, ARCHIVE_OK,
	    archive_read_open_memory(a, archive_pkware_unix,
		sizeof(archive_pkware_unix)));
	assertEqualIntA(a, ARCHIVE_OK, archive_read_next_header(a, &ae));

	assertEqualString("test.txt", archive_entry_pathname(ae));
	assertEqualInt(-86400, archive_entry_mtime(ae));
	assertEqualInt(-172800, archive_entry_atime(ae));
	assertEqualInt(1001, archive_entry_uid(ae));
	assertEqualInt(1002, archive_entry_gid(ae));

	assertEqualIntA(a, ARCHIVE_OK, archive_read_close(a));
	assertEqualInt(ARCHIVE_OK, archive_read_free(a));
}

