#include "test.h"

/*
 * Regression tests for pre-1970 (negative) Unix timestamps in the three
 * extra fields that carry them: 0x000D (PKWARE Unix), 0x5455 (Info-Zip
 * "UT" extended timestamp), and 0x5855 (Info-Zip "UX", old version).
 *
 * `archive_le32dec()` returns an unsigned `uint32_t`; decoding these
 * fields by assigning that result directly to a signed `time_t` zero-
 * extends instead of sign-extends, turning any negative timestamp into
 * one about 2^32 seconds (~136 years) in the future. Each archive below
 * has a single entry ("test.txt") with mtime = -86400 (1969-12-31
 * 00:00:00 UTC) and atime = -172800 (1969-12-30 00:00:00 UTC); the UT
 * variant also sets ctime = -259200 (1969-12-29 00:00:00 UTC).
 */

