struct streaming_buffer {
	const unsigned char *data;
	size_t size;
	size_t offset;
};

static la_ssize_t
read_streaming_buffer(struct archive *a, void *client_data, const void **buffer)
{
	struct streaming_buffer *stream = client_data;
	size_t available;

	(void)a;
	if (stream->offset == stream->size) {
		*buffer = NULL;
		return (0);
	}
	available = stream->size - stream->offset;
	if (available > 17)
		available = 17;
	*buffer = stream->data + stream->offset;
	stream->offset += available;
	return ((la_ssize_t)available);
}

DEFINE_TEST(test_read_format_zip_streamable_skip)
{
	struct streaming_buffer stream = {
		archive_data, sizeof(archive_data), 0
	};
	struct archive_entry *entry;
	struct archive *a;

	assert((a = archive_read_new()) != NULL);
	assertEqualIntA(a, ARCHIVE_OK,
	    archive_read_support_format_zip_streamable(a));
	assertEqualIntA(a, ARCHIVE_OK, archive_read_open2(a, &stream, NULL,
	    read_streaming_buffer, NULL, NULL));
	assertEqualIntA(a, ARCHIVE_OK, archive_read_next_header(a, &entry));
	assertEqualString("blocked.txt", archive_entry_pathname(entry));
	assertEqualIntA(a, ARCHIVE_OK, archive_read_data_skip(a));
	assertEqualIntA(a, ARCHIVE_EOF, archive_read_next_header(a, &entry));
	assertEqualIntA(a, ARCHIVE_OK, archive_read_close(a));
	assertEqualInt(ARCHIVE_OK, archive_read_free(a));
}
